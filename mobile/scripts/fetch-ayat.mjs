#!/usr/bin/env node
/**
 * Regenerates src/data/ayat.ts: the curated ayat shown in prayer notifications and on launch.
 *
 * Text is fetched verbatim from AlQuran Cloud (Tanzil), the same editions the reader uses
 * (src/lib/quran.ts EDITIONS), so it is never typed by hand. Notifications are scheduled days
 * ahead and must show the ayah offline, which is why these few verses are bundled.
 *
 *   node scripts/fetch-ayat.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const EDITIONS = ['quran-uthmani', 'en.sahih', 'ur.jalandhry'];

/** Read at prayer time: establishing prayer, patience and prayer, prayer and remembrance. */
const PRAYER = ['2:43', '2:45', '2:153', '2:238', '11:114', '14:40', '17:78', '20:14', '2:110', '108:2'];
/** Shown on launch: prayer, remembrance of Allah, hope and worship. */
const LAUNCH = ['2:152', '13:28', '39:53', '94:5', '2:186', '51:56', '33:41', '3:139', '93:5', '29:69', '50:16', '73:8', '2:153', '20:14', '29:45', '7:205'];

async function ayah(ref) {
  const res = await fetch(`https://api.alquran.cloud/v1/ayah/${ref}/editions/${EDITIONS.join(',')}`);
  if (!res.ok) throw new Error(`${ref}: HTTP ${res.status}`);
  const { code, data } = await res.json();
  if (code !== 200 || !Array.isArray(data) || data.length !== 3) throw new Error(`${ref}: bad response`);
  const [s, a] = ref.split(':').map(Number);
  data.forEach((d, i) => {
    if (d.edition.identifier !== EDITIONS[i] || d.surah.number !== s || d.numberInSurah !== a || !d.text.trim()) throw new Error(`${ref}: unexpected ${d.edition.identifier}`);
  });
  return { s, a, ar: data[0].text, en: data[1].text, ur: data[2].text };
}

const refs = [...new Set([...PRAYER, ...LAUNCH])];
// One at a time: the API rate-limits bursts.
const all = {};
for (const r of refs) {
  all[r] = await ayah(r);
  await new Promise(ok => setTimeout(ok, 400));
}
const list = rs => rs.map(r => `  ${JSON.stringify(all[r])},`).join('\n');

const out = `/**
 * GENERATED by scripts/fetch-ayat.mjs — do not edit by hand.
 *
 * Verbatim from AlQuran Cloud (Tanzil): Arabic quran-uthmani, English en.sahih (Saheeh
 * International), Urdu ur.jalandhry (Fateh Muhammad Jalandhry) — the same editions as the reader.
 */
export type Ayah = { s: number; a: number; ar: string; en: string; ur: string };

export const AYAT_CREDIT = 'Arabic: Tanzil (Uthmani) · English: Saheeh International · Urdu: Jalandhry';

/** Read at prayer time. */
export const PRAYER_AYAT: Ayah[] = [
${list(PRAYER)}
];

/** Shown when the app opens: prayer, remembrance, hope and worship. */
export const LAUNCH_AYAT: Ayah[] = [
${list(LAUNCH)}
];
`;
const file = join(dirname(fileURLToPath(import.meta.url)), '../src/data/ayat.ts');
writeFileSync(file, out);
console.log(`Wrote ${refs.length} ayat to ${file}`);
